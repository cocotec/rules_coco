#!/usr/bin/env python3
"""Stage popili into ./staged for the local_toolchain e2e. See tools/stage_popili.py.

Also writes the licence protocol version the staged popili reads into ./staged, for
MODULE.bazel (coco.MODULE.bazel) and WORKSPACE (license.bzl) to pass to the local toolchain.
"""

import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_HERE, "..", "..", "tools"))
import stage_popili  # noqa: E402

_STAGED = os.path.join(_HERE, "staged")

version = stage_popili.main(_STAGED, binary_subdir="popili", with_cpp_runtime=True)
protocol = stage_popili.license_protocol_version(version)
generated = f"# Generated by stage.py for popili {version}.\n"

with open(os.path.join(_STAGED, "BUILD.bazel"), "w") as f:
    f.write(generated)
with open(os.path.join(_STAGED, "license.bzl"), "w") as f:
    f.write(generated + f'"""The licence protocol version of the staged popili."""\n\nLICENSE_PROTOCOL_VERSION = {protocol}\n')
with open(os.path.join(_STAGED, "coco.MODULE.bazel"), "w") as f:
    f.write(generated + f"""coco = use_extension("@rules_coco//coco:extensions.bzl", "coco")
coco.local_toolchain(
    cc_runtime = "staged/cpp-runtime",
    license_protocol_version = {protocol},
    popili = "staged/popili",
)
""")
