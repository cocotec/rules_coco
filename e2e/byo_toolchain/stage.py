#!/usr/bin/env python3
"""Stage popili into ./popili_dist/bin for the byo_toolchain e2e. See tools/stage_popili.py.

Also writes the staged popili version and its licence protocol version into
./popili_dist/bin/version.bzl, for tools/BUILD.bazel to declare on the toolchain, and the
coco_license_repository acquiring that protocol version's licence with the staged server into
./popili_dist/bin/licence.MODULE.bazel, which MODULE.bazel includes.
"""

import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_HERE, "..", "..", "tools"))
import stage_popili  # noqa: E402

_DIST = os.path.join(_HERE, "popili_dist")

version = stage_popili.main(_DIST, binary_subdir="bin")

protocol = stage_popili.license_protocol_version(version)

with open(os.path.join(_DIST, "bin", "version.bzl"), "w") as f:
    f.write(
        f'"""Generated by stage.py: the version of the staged popili."""\n\n'
        f'POPILI_VERSION = "{version}"\n'
        f"LICENSE_PROTOCOL_VERSION = {protocol}\n"
    )

with open(os.path.join(_DIST, "bin", "licence.MODULE.bazel"), "w") as f:
    f.write(
        "# Generated by stage.py: under local_acquire, the staged popili's licence, acquired with its own server.\n"
        'coco_license_repository = use_repo_rule("@rules_coco//coco:repositories.bzl", "coco_license_repository")\n\n'
        "coco_license_repository(\n"
        '    name = "byo_licence",\n'
        '    popili = "popili_dist/bin",\n'
        f"    protocol_version = {protocol},\n"
        ")\n"
    )
